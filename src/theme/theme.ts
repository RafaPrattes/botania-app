export function getGreetingByHour(lang: AppLanguage): string {
  const hour = new Date().getHours();
  if (lang === 'en') {
    if (hour < 12) return 'GOOD MORNING';
    if (hour < 18) return 'GOOD AFTERNOON';
    return 'GOOD EVENING';
  }
  if (lang === 'es') {
    if (hour < 12) return 'BUENOS DÍAS';
    if (hour < 18) return 'BUENAS TARDES';
    return 'BUENAS NOCHES';
  }
  if (hour < 12) return 'BOM DIA';
  if (hour < 18) return 'BOA TARDE';
  return 'BOA NOITE';
}

export function getGardenerRank(level: number, lang: AppLanguage): string {
  if (lang === 'en') {
    if (level <= 1) return 'Seedling Keeper';
    if (level === 2) return 'Leaf Nurturer';
    if (level === 3) return 'Sprout Guardian';
    return 'Botanical Master';
  }
  if (lang === 'es') {
    if (level <= 1) return 'Cuidadora de semillas';
    if (level === 2) return 'Amiga de las hojas';
    if (level === 3) return 'Guardiana de brotes';
    return 'Maestra botánica';
  }
  if (level <= 1) return 'Cultivadora iniciante';
  if (level === 2) return 'Cuidadora de folhas';
  if (level === 3) return 'Guardiã de brotos';
  return 'Mestra botânica';
}

